"""Local temporary HTTP probe: no camera, no saved real credential, no retries.

Reproduce separately transmitted POST headers/body and verify rejected requests
preserve their HTTP status on Windows. The temporary token is generated by the
normal OfficeClient and is never read or printed by this script.
"""
from collections import Counter
import http.client
import json
from pathlib import Path
import sys
import tempfile
import time
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from pipe_twin.capture_agent import CaptureAgentError, submit_remote_capture
from pipe_twin.office_client import OfficeClient, OfficeClientConfig


def camera_forbidden(**kwargs):
    raise AssertionError('No camera may be opened by the auth rejection probe')


def main():
    original_send = http.client.HTTPConnection.send
    summary = {}
    with tempfile.TemporaryDirectory(prefix='pipe-auth-probe-') as directory:
        root = Path(directory)
        client = OfficeClient(OfficeClientConfig(
            bind='127.0.0.1', capture_port=0, file_port=0, require_token=True,
            token_file=root/'auth.token', output_root=root/'runs'), capture_fn=camera_forbidden)
        details = client.start()
        try:
            for delay in (0., .005, .02):
                outcomes = Counter()
                def send(connection, data):
                    if isinstance(data, bytes) and data.startswith(b'{'):
                        time.sleep(delay)
                    return original_send(connection, data)
                with patch.object(http.client.HTTPConnection, 'send', send):
                    for _ in range(40):
                        try:
                            submit_remote_capture(details['capture_url'], None, {'count': 1})
                            outcomes['unexpected_success'] += 1
                        except CaptureAgentError as error:
                            message = str(error)
                            outcomes['401' if '(401)' in message else message] += 1
                summary[str(delay)] = dict(outcomes)
        finally:
            client.stop()
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
